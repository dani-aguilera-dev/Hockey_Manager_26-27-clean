type Params = Record<string, string | number>

interface LanguageValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (text: string, params?: Params) => string
}

const LanguageContext = createContext<LanguageValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    try {
      return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'es'
    } catch {
      return 'es'
    }
  })

  useEffect(() => {
    document.documentElement.lang = lang
    try {
      localStorage.setItem(STORAGE_KEY, lang)
    } catch {
      // Sin persistencia si el navegador bloquea localStorage.
    }
  }, [lang])

  const t = useCallback(
    (text: string, params?: Params) => {
      let output = lang === 'en' ? EN[text] ?? text : text
      if (params) {
        for (const [key, value] of Object.entries(params)) {
          output = output.replaceAll(`{${key}}`, String(value))
        }
      }
      return output
    },
    [lang],
  )

  return <LanguageContext.Provider value={{ lang, setLang, t }}>{children}</LanguageContext.Provider>
}

export function useLanguage(): LanguageValue {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage debe usarse dentro de LanguageProvider')
  return value
}
